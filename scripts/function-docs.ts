import { CATEGORY_ORDER, ERROR_EXPLANATIONS, FUNCTION_LIST, signature, type ErrorCode } from '../src/engine';

const escape = (s: string) => s.replace(/\|/g, '\\|');

/** Markdown reference of every supported function, grouped by category. */
export function renderFunctionDocs(): string {
  const out: string[] = [];
  out.push('# Supported functions');
  out.push('');
  out.push('<!-- Generated by `npm run docs:functions` from src/engine/functions. Do not edit by hand. -->');
  out.push('');
  out.push(
    `Gridline implements **${FUNCTION_LIST.length} functions** with its own evaluator (no third-party formula engine). ` +
      'Arguments in `[brackets]` are optional; `...` means the previous argument can repeat.',
  );
  out.push('');
  out.push('| Category | Count | Functions |');
  out.push('| --- | ---: | --- |');
  for (const cat of CATEGORY_ORDER) {
    const fs = FUNCTION_LIST.filter((f) => f.category === cat);
    out.push(`| [${cat}](#${cat.toLowerCase()}) | ${fs.length} | ${fs.map((f) => f.name).join(', ')} |`);
  }
  out.push('');

  for (const cat of CATEGORY_ORDER) {
    out.push(`## ${cat}`);
    out.push('');
    out.push('| Function | Description | Example |');
    out.push('| --- | --- | --- |');
    for (const f of FUNCTION_LIST.filter((fn) => fn.category === cat)) {
      const flags = f.volatile ? ' *(volatile)*' : '';
      out.push(`| \`${escape(signature(f))}\` | ${escape(f.description)}${flags} | \`${escape(f.example)}\` |`);
    }
    out.push('');
  }

  out.push('## Operators');
  out.push('');
  out.push('From lowest to highest precedence (same as Excel):');
  out.push('');
  out.push('| Operator | Meaning | Example |');
  out.push('| --- | --- | --- |');
  out.push('| `=` `<>` `<` `>` `<=` `>=` | Comparison (text is compared case-insensitively) | `=A1>=10` |');
  out.push('| `&` | Text concatenation | `=A1 & " " & B1` |');
  out.push('| `+` `-` | Addition, subtraction | `=A1-B1` |');
  out.push('| `*` `/` | Multiplication, division | `=A1/B1` |');
  out.push('| `^` | Exponentiation (left-associative: `2^3^2` = 64) | `=2^10` |');
  out.push('| `%` | Postfix percent | `=50%` |');
  out.push('| `-` `+` (prefix) | Negation; binds tighter than `^`, so `-2^2` = 4 | `=-A1` |');
  out.push('| `:` | Range: `A1:B5`, whole columns `A:C`, whole rows `2:5` | `=SUM(A:A)` |');
  out.push('');

  out.push('## Criteria syntax (COUNTIF, SUMIF, AVERAGEIF, COUNTIFS, SUMIFS)');
  out.push('');
  out.push('| Criterion | Matches |');
  out.push('| --- | --- |');
  out.push('| `5` or `"5"` | Cells equal to 5 |');
  out.push('| `">10"`, `"<=3"`, `"<>0"` | Numeric comparison |');
  out.push('| `"apple"` | Text equal to apple (case-insensitive) |');
  out.push('| `"a*"`, `"?at"` | Wildcards: `*` any characters, `?` one character, `~*` a literal `*` |');
  out.push('| `"<>apple"` | Anything except apple |');
  out.push('| `""` / `"="` | Empty cells |');
  out.push('| `"<>"` | Non-empty cells |');
  out.push('');

  out.push('## Error values');
  out.push('');
  out.push('| Error | Meaning |');
  out.push('| --- | --- |');
  for (const [code, text] of Object.entries(ERROR_EXPLANATIONS) as Array<[ErrorCode, string]>) {
    out.push(`| \`${code}\` | ${text} |`);
  }
  out.push('');
  return out.join('\n');
}
